#!/usr/bin/env python3
"""Generate public/assets/css/tech-store.css: dark-theme colour overrides for the shop, account,
portfolio and blog styles (written for white pages in pages.css and vibe.css).
Re-run after changing those styles:  python3 scripts/dark-store-css.py"""
import re, pathlib
root = pathlib.Path(__file__).resolve().parent.parent
css = root / 'public/assets/css'

def chunk(path, start_marker=None, prefixes=None):
    t = (css / path).read_text()
    if start_marker:
        t = t[t.index(start_marker):]
    t = re.sub(r'/\*.*?\*/', '', t, flags=re.S)
    out = []
    # flatten simple rules (skip @keyframes / @property; descend into @media)
    for m in re.finditer(r'(@media[^{]+)\{((?:[^{}]*\{[^{}]*\})*)\s*\}|([^{}@]+)\{([^{}]*)\}', t):
        if m.group(1):
            inner = [(sel.strip(), body) for sel, body in re.findall(r'([^{}]+)\{([^{}]*)\}', m.group(2))]
            out.append((m.group(1).strip(), inner))
        else:
            out.append((None, [(m.group(3).strip(), m.group(4))]))
    res = []
    for media, rules in out:
        conv = []
        for sel, body in rules:
            sels = [s.strip() for s in sel.split(',') if s.strip()]
            if prefixes:
                sels = [s for s in sels if any(s.startswith(p) for p in prefixes)]
            if not sels or any(s.startswith(('from', 'to', '0%')) or re.match(r'^\d', s) for s in sels):
                continue
            decl = convert(body)
            if decl:
                conv.append(',\n'.join('.theme-dark ' + s.replace('.sc-light ', '') for s in sels) + ' { ' + decl + ' }')
        if conv:
            res.append((media + ' {\n' + '\n'.join(conv) + '\n}') if media else '\n'.join(conv))
    return '\n'.join(res)

INK = '#eef0ff'
TEXT = { '#17112e': INK, 'var(--vb-ink)': INK, '#4b4763': 'rgba(230,232,255,.8)', '#5a5570': 'rgba(230,232,255,.75)', '#4d4766': 'rgba(230,232,255,.78)',
         '#3d3756': 'rgba(230,232,255,.85)', '#5a5470': 'rgba(230,232,255,.72)', '#7a7590': 'rgba(220,224,255,.6)', '#6b6680': 'rgba(220,224,255,.6)', '#9a94b8': 'rgba(220,224,255,.5)',
         '#146c34': '#4ade80', '#8a5300': '#facc15', '#b4232f': '#ff8a98', '#e8452f': '#ff8a5c', '#E8452F': '#ff8a5c' }
BG = { '#fff': 'rgba(255,255,255,.045)', '#ffffff': 'rgba(255,255,255,.045)', '#fbfaff': 'rgba(255,255,255,.04)', '#f4f2fa': 'rgba(255,255,255,.06)', '#f6f4fc': 'rgba(255,255,255,.06)',
       '#fdfcff': 'transparent', '#fffbeb': 'rgba(250,204,21,.1)', '#ecfdf3': 'rgba(34,197,94,.12)', '#fff1f2': 'rgba(255,82,102,.12)', '#eef2ff': 'rgba(99,102,241,.14)',
       'rgba(255,255,255,.92)': 'rgba(12,14,32,.88)', 'rgba(255,255,255,.9)': 'rgba(12,14,32,.82)', 'rgba(255,255,255,.85)': 'rgba(255,255,255,.05)', 'rgba(255,255,255,.75)': 'rgba(255,255,255,.06)' }

def convert(body):
    keep = []
    for d in body.split(';'):
        if ':' not in d:
            continue
        k, v = [x.strip() for x in d.split(':', 1)]
        nv = v
        if k == 'color' or k == '-webkit-text-fill-color':
            nv = TEXT.get(v, v)
        elif k in ('background', 'background-color'):
            if v in BG: nv = BG[v]
            else:
                nv = re.sub(r'linear-gradient\(rgba\(255,255,255,\.9\), rgba\(255,255,255,\.9\)\)', 'linear-gradient(rgba(12,14,32,.85), rgba(12,14,32,.85))', v)
                nv = re.sub(r'linear-gradient\(#fff, #fff\)', 'linear-gradient(#0b0d1f, #0b0d1f)', nv)
        elif k.startswith('border') or k == 'outline':
            nv = re.sub(r'rgba\(23,\s*17,\s*46,\s*\.?(\d+)\)', lambda m: 'rgba(255,255,255,%s)' % ('.%s' % m.group(1) if '.' not in m.group(1) else m.group(1)), v)
            nv = nv.replace('#fff', 'rgba(255,255,255,.12)') if 'solid #fff' in nv or k == 'border-color' and v == '#fff' else nv
        elif k == 'box-shadow':
            nv = re.sub(r'rgba\(23,\s*17,\s*46,\s*(\.\d+)\)', lambda m: 'rgba(0,0,0,%.2f)' % min(.8, float(m.group(1)) * 2.2), v)
        else:
            continue
        if nv != v:
            keep.append(f'{k}: {nv}')
    return '; '.join(keep) + (';' if keep else '')

head = '/* GENERATED by scripts/dark-store-css.py — dark colours for shop, account, portfolio, blog and product pages. Do not edit by hand. */\n'
a = chunk('pages.css', 'Store, account, portfolio and blog pages')
b = chunk('vibe.css', None, ['.vp-', '.sp-', '.st-', '.vb-marquee.st-pills', '.st-pop', '.sc-light .st-pop'])
(css / 'tech-store.css').write_text(head + a + '\n' + b + '\n')
print('ok', len(a) + len(b))
